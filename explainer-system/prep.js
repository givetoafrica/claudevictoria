// PREP: turns videos/<name>/script.json + its narration clips into the timeline the film and the song both read.
//   node prep.js <name>
// It writes active.js (script + timeline) and needs-narration.json (any clip that has no mp3 yet).
// Narration clips live in videos/<name>/narration/<scene-id>.mp3 (one clip per scene), or <scene-id>-1.mp3, -2.mp3 ...
// when a scene's "voiceover" is an array (a quiz question and its answer, say).
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const name = process.argv[2];
if (!name) { console.error('usage: node prep.js <video-name>'); process.exit(1); }
const dir = path.join(__dirname, 'videos', name);
const script = JSON.parse(fs.readFileSync(path.join(dir, 'script.json'), 'utf8'));

const BPM = 96, BEAT = 60 / BPM;
const ceilBeat = (t) => Math.ceil(t / BEAT - 1e-9) * BEAT;
const probe = (f) => {
  const r = spawnSync(process.env.FFPROBE_PATH || 'ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f], { encoding: 'utf8' });
  return r.status === 0 ? parseFloat(r.stdout) : null;
};

const missing = [];
const scenes = [];
let cursor = 0; // the end of the previous scene
script.scenes.forEach((sc, i) => {
  const texts = Array.isArray(sc.voiceover) ? sc.voiceover : [sc.voiceover || ''];
  const gaps = sc.gaps || [];
  const t0 = i === 0 ? 0 : ceilBeat(cursor + 0.6);
  let t = t0 + (sc.lead ?? 0.5); // a beat of picture before the voice starts
  const clips = [];
  texts.forEach((text, k) => {
    const rel = path.join('videos', name, 'narration', texts.length > 1 ? `${sc.id}-${k + 1}.mp3` : `${sc.id}.mp3`);
    const abs = path.join(__dirname, rel);
    let dur = fs.existsSync(abs) ? probe(abs) : null;
    if (dur == null) { missing.push({ scene: sc.id, clip: k + 1, file: rel, text }); dur = Math.max(2, text.split(/\s+/).length / 2.5); } // an estimate until the real clip exists
    if (k > 0) t += gaps[k - 1] ?? 0.4;
    clips.push({ file: rel, text, at: +t.toFixed(3), dur: +dur.toFixed(3) });
    t += dur;
  });
  const end = t + (sc.tail ?? 0.4);
  cursor = end;
  scenes.push({ id: sc.id, type: sc.type, t0: +t0.toFixed(3), end: +end.toFixed(3), clips });
});
// each scene runs until the next one starts
scenes.forEach((s, i) => { s.t1 = i + 1 < scenes.length ? scenes[i + 1].t0 : +(s.end + (script.outro ?? 3.5)).toFixed(3); });
const duration = scenes[scenes.length - 1].t1;

const active = { name, script, timeline: { bpm: BPM, scenes, duration } };
const body = JSON.stringify(active);
fs.writeFileSync(path.join(__dirname, 'active.js'), `// generated by prep.js (node prep.js ${name}), do not edit\n(function(){const A=${body};if(typeof module!=='undefined')module.exports=A;else globalThis.ACTIVE=A;})();\n`);
fs.writeFileSync(path.join(__dirname, 'needs-narration.json'), JSON.stringify(missing, null, 2));
console.log(`${name}: ${scenes.length} scenes, ${duration.toFixed(1)}s (${(duration / 60).toFixed(1)} min), ${missing.length} narration clip(s) missing${missing.length ? ' -> see needs-narration.json' : ''}`);
